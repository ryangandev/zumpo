// What audio:build and audio:check share: where things are, the loudness
// classes, validating audio/sounds.json, and writing the generated modules
// from the manifest. Nothing here runs ffmpeg.

import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';

export const REPO = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '../..',
);

/** Where a repository (the real one, or a test's copy) keeps each piece. */
export function repoPaths(repo = REPO) {
  const outDir = path.join(repo, 'client', 'src', 'audio', 'generated');
  return {
    sounds: path.join(repo, 'audio', 'sounds.json'),
    schema: path.join(repo, 'audio', 'sounds.schema.json'),
    outDir,
    filesDir: path.join(outDir, 'files'),
    manifest: path.join(outDir, 'manifest.json'),
    // Where a build stages the next generated folder; never inside client/.
    staging: path.join(repo, '.audio-build'),
  };
}

/**
 * The masters live outside the repository (no Git LFS, no cost): on Ryan's
 * Mac mini by default, anywhere ZUMPO_AUDIO_DIR says.
 */
export function mastersRoot(env = process.env) {
  const configured = env.ZUMPO_AUDIO_DIR?.trim();
  const root = configured || '~/Documents/assets/zumpo-audio';
  return path.resolve(root.replace(/^~(?=$|\/)/, os.homedir()));
}

/**
 * Bump when the build's processing changes in a way that should re-encode
 * every sound; the encode key carries it.
 */
export const PIPELINE = 1;

/**
 * The loudness classes: the momentary-loudness maximum (400 ms window) each
 * is normalised to, its longest length and the most bytes either encoded file
 * may take. From the self-production report's starting points.
 */
export const CLASSES = {
  ui: { targetLufs: -22, maxSeconds: 1, maxBytes: 30 * 1024 },
  event: { targetLufs: -16, maxSeconds: 2, maxBytes: 30 * 1024 },
  stinger: { targetLufs: -15, maxSeconds: 5, maxBytes: 80 * 1024 },
};

/**
 * Past this many dB under its class target, a sound is heard as quieter than
 * the rest of its class: its master needs a gentler peak, not more gain.
 */
export const MAX_LOUDNESS_GAP = 6;

/**
 * How far under its class target each sound lands, by class: the worst of its
 * variants and formats, in dB, as the decoded files measure. Only gaps of
 * half a dB or more are listed, past what encoding moves, the widest first.
 */
export function loudnessGaps(manifest) {
  const byClass = Object.fromEntries(
    Object.keys(CLASSES).map((name) => [name, { count: 0, under: [] }]),
  );
  for (const [id, { declared, variants }] of Object.entries(manifest.sounds)) {
    const entry = byClass[declared.loudness];
    entry.count += 1;
    const target = CLASSES[declared.loudness].targetLufs;
    let gap = 0;
    for (const { loudness } of variants) {
      for (const lufs of Object.values(loudness.momentaryMax)) {
        gap = Math.max(gap, target - lufs);
      }
    }
    if (gap >= 0.5) entry.under.push({ id, gap: Math.round(gap * 10) / 10 });
  }
  for (const entry of Object.values(byClass)) {
    entry.under.sort((a, b) => b.gap - a.gap || a.id.localeCompare(b.id));
  }
  return byClass;
}

/** `loudnessGaps` as lines for people, a gap past the limit marked with "!". */
export function loudnessSummary(manifest) {
  const lines = [
    `loudness: dB under each class target (worst variant; ! past ${MAX_LOUDNESS_GAP} dB)`,
  ];
  for (const [name, { count, under }] of Object.entries(
    loudnessGaps(manifest),
  )) {
    if (count === 0) continue;
    const list = under
      .map(({ id, gap }) => `${id} ${gap}${gap > MAX_LOUDNESS_GAP ? '!' : ''}`)
      .join(', ');
    lines.push(
      `  ${name} (${CLASSES[name].targetLufs} LUFS): ${count - under.length} of ${count} on target${list ? `; under: ${list}` : ''}`,
    );
  }
  return lines;
}

/** No decoded file may peak above this many dBTP. */
export const TRUE_PEAK_CEILING = -1;
/** The gain leaves this much true-peak room before encoding, which adds some. */
export const PRE_ENCODE_CEILING = -1.5;

/** Bitrates by channel count, for AAC (aac_at) and Opus (libopus). */
export const BITRATES = {
  1: { m4a: '96k', webm: '64k' },
  2: { m4a: '128k', webm: '96k' },
};

export const NOTICE =
  'Generated by tools/audio from audio/sounds.json and the masters. Do not edit.';

export const sha256 = (bytes) =>
  crypto.createHash('sha256').update(bytes).digest('hex');

export const fileSha256 = (file) => sha256(fs.readFileSync(file));

/**
 * What an encoded variant was made from and how: the master and every
 * parameter of the processing, and nothing the build only checks (a class's
 * length and size limits). A variant whose key has not changed is not encoded
 * again, so tuning `gainDb` or `minGapMs` needs no masters and no ffmpeg.
 */
export function encodeKey({ sourceSha256, loudness, channels }) {
  return sha256(
    JSON.stringify({
      pipeline: PIPELINE,
      sourceSha256,
      targetLufs: CLASSES[loudness].targetLufs,
      channels,
      bitrates: BITRATES[channels],
      ceilings: [TRUE_PEAK_CEILING, PRE_ENCODE_CEILING],
    }),
  );
}

/** `masters/snap-took/2.wav` -> 2 */
export function variantNumber(file) {
  return Number(/\/(\d+)\.wav$/.exec(file)?.[1]);
}

/** The encoded file's name in generated/files/. */
export function outputName(id, file, format) {
  return `${id}-${variantNumber(file)}.${format}`;
}

/** `draw-and-guess` -> `drawAndGuessSounds` */
export function bankExport(group) {
  return `${group.replaceAll(/-(\w)/g, (_, c) => c.toUpperCase())}Sounds`;
}

/** Keys sorted, so two equal values serialise the same. */
export function canonical(value) {
  if (Array.isArray(value)) return value.map(canonical);
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.keys(value)
        .toSorted()
        .map((key) => [key, canonical(value[key])]),
    );
  }
  return value;
}

export const sameValue = (a, b) =>
  JSON.stringify(canonical(a)) === JSON.stringify(canonical(b));

export function readJson(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

/** `/sounds/2/origin/url` -> `sounds[2] (snap-took).origin.url` */
function describePath(doc, instancePath) {
  let label = '';
  let node = doc;
  for (const part of instancePath.split('/').slice(1)) {
    node = node?.[part];
    if (/^\d+$/.test(part)) {
      label += `[${part}]`;
      if (typeof node?.id === 'string') label += ` (${node.id})`;
    } else label += label ? `.${part}` : part;
  }
  return label || 'the file';
}

function describeError(doc, error) {
  const where = describePath(doc, error.instancePath);
  switch (error.keyword) {
    case 'additionalProperties':
      return `${where} has an unknown field "${error.params.additionalProperty}"`;
    case 'required':
      return `${where} is missing "${error.params.missingProperty}"`;
    case 'enum':
      return `${where} must be one of ${error.params.allowedValues.map((v) => JSON.stringify(v)).join(', ')}`;
    case 'const':
      return `${where} must be ${JSON.stringify(error.params.allowedValue)}`;
    default:
      return `${where} ${error.message}`;
  }
}

/**
 * Every way `doc` breaks the schema or the rules the schema cannot say, as
 * sentences; empty when it is valid.
 */
export function validateSounds(doc, schema) {
  const ajv = new Ajv2020({ allErrors: true, strict: true });
  const validate = ajv.compile(schema);
  if (!validate(doc)) {
    return validate.errors
      .filter((error) => error.keyword !== 'if')
      .map((error) => `audio/sounds.json: ${describeError(doc, error)}`);
  }
  const problems = [];
  const ids = new Set();
  for (const sound of doc.sounds) {
    const where = `audio/sounds.json: ${sound.id}`;
    if (ids.has(sound.id)) problems.push(`${where} is declared twice`);
    ids.add(sound.id);
    // The production build refuses files named test-*, so a fixture's name
    // is what keeps it out.
    if ((sound.group === 'test') !== sound.id.startsWith('test-')) {
      problems.push(
        `${where}: a sound is in the test group exactly when its id starts with test-`,
      );
    }
    const files = new Set();
    for (const variant of sound.variants) {
      if (!variant.file.startsWith(`masters/${sound.id}/`)) {
        problems.push(
          `${where}: ${variant.file} is not under masters/${sound.id}/`,
        );
      }
      if (files.has(variant.file)) {
        problems.push(`${where}: ${variant.file} is listed twice`);
      }
      files.add(variant.file);
    }
    // A step is played by number; a detune would blur the run it climbs.
    if (sound.steps && sound.pitchSpread !== undefined) {
      problems.push(`${where}: a stepped sound takes no pitchSpread`);
    }
    if (sound.steps && sound.variants.length < 2) {
      problems.push(`${where}: a stepped sound needs at least two steps`);
    }
    // The schema says so too; kept here so the rule is plain in the check.
    if (!['CC0-1.0', 'own'].includes(sound.origin.license)) {
      problems.push(
        `${where}: the license ${sound.origin.license} is not allowed`,
      );
    }
  }
  // "Your turn" is the one sound a hidden page may make.
  const hidden = doc.sounds.filter((sound) => sound.hiddenTab);
  if (hidden.length > 1) {
    problems.push(
      `audio/sounds.json: only one sound may play in a hidden tab, not ${hidden.map((sound) => sound.id).join(', ')}`,
    );
  }
  return problems;
}

/** What the engine needs of one sound, in the order it is written. */
function specOf(sound, variants) {
  const spec = {
    id: sound.id,
    group: sound.group,
    loudness: sound.loudness,
    gainDb: sound.gainDb,
  };
  for (const key of [
    'steps',
    'pitchSpread',
    'minGapMs',
    'maxVoices',
    'hiddenTab',
  ]) {
    if (sound[key] !== undefined) spec[key] = sound[key];
  }
  spec.variants = variants;
  return spec;
}

const quote = (value) => `'${value}'`;

function renderBank(group, sounds) {
  const lines = [
    `// ${NOTICE}`,
    `import type { SoundBank } from '../types';`,
    '',
    `export const ${bankExport(group)} = {`,
  ];
  for (const { declared, variants } of sounds) {
    const spec = specOf(declared, null);
    lines.push(`  ${quote(spec.id)}: {`);
    for (const [key, value] of Object.entries(spec)) {
      if (key === 'variants') continue;
      lines.push(
        `    ${key}: ${typeof value === 'string' ? quote(value) : value},`,
      );
    }
    lines.push('    variants: [');
    for (const variant of variants) {
      lines.push('      {');
      for (const format of ['m4a', 'webm']) {
        lines.push(
          `        ${format}: new URL('./files/${variant.files[format].file}', import.meta.url).href,`,
        );
      }
      lines.push(`        duration: ${variant.duration},`);
      lines.push('      },');
    }
    lines.push('    ],');
    lines.push('  },');
  }
  lines.push('} satisfies SoundBank;', '');
  return lines.join('\n');
}

function renderIndex(manifest) {
  const ids = Object.keys(manifest.sounds).toSorted();
  const groups = [
    ...new Set(ids.map((id) => manifest.sounds[id].declared.group)),
  ].toSorted();
  const lines = [
    `// ${NOTICE}`,
    `import type { SoundBank } from '../types';`,
    '',
    '/** Every declared sound. */',
    `export const SOUND_IDS = [${ids.map(quote).join(', ')}] as const;`,
    'export type SoundId = (typeof SOUND_IDS)[number];',
    '',
    '/** The groups that have sounds; each is a bank, a module of its own. */',
    `export type SoundGroup = ${groups.length ? groups.map(quote).join(' | ') : 'never'};`,
    '',
    '/** Each bank, loaded when asked for, as the development sound lab does. */',
    'export const SOUND_BANKS: Record<SoundGroup, () => Promise<SoundBank>> = {',
    ...groups.map(
      (group) =>
        `  ${quote(group)}: () => import('./${group}').then((bank) => bank.${bankExport(group)}),`,
    ),
    '};',
    '',
  ];
  return lines.join('\n');
}

/**
 * Every generated module, by its name in generated/: one bank per group that
 * has sounds, and the index of ids and banks.
 */
export function renderModules(manifest) {
  const byGroup = new Map();
  for (const id of Object.keys(manifest.sounds).toSorted()) {
    const sound = manifest.sounds[id];
    const group = sound.declared.group;
    if (!byGroup.has(group)) byGroup.set(group, []);
    byGroup.get(group).push(sound);
  }
  const modules = new Map([['index.ts', renderIndex(manifest)]]);
  for (const [group, sounds] of byGroup) {
    modules.set(`${group}.ts`, renderBank(group, sounds));
  }
  return modules;
}

export function serializeManifest(manifest) {
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

/** Whether a file begins as its container does: MP4's `ftyp` box, WebM's EBML header. */
const CONTAINERS = {
  m4a: (content) => content.subarray(4, 8).toString('latin1') === 'ftyp',
  webm: (content) =>
    content.subarray(0, 4).equals(Buffer.from([0x1a, 0x45, 0xdf, 0xa3])),
};

/** Each variant's master and its hash, in order, from either side. */
const masters = (variants, file, sha) =>
  variants.map((variant) => `${variant[file]} ${variant[sha]}`);

const FIX =
  'Run `npm run audio:build` where the masters are (ZUMPO_AUDIO_DIR), and commit what it writes.';

/**
 * Whether the generated folder is exactly what sounds.json and the masters
 * it names make, without the masters: sounds.json is valid, the manifest
 * declares the same sounds, every encoded file is there with the hash the
 * manifest records and nothing else is, and the modules are current.
 * Returns the problems as sentences.
 */
export function checkGenerated(repo = REPO) {
  const paths = repoPaths(repo);
  const problems = [];
  let doc;
  try {
    doc = readJson(paths.sounds);
  } catch (error) {
    return [`audio/sounds.json cannot be read: ${error.message}`];
  }
  const invalid = validateSounds(doc, readJson(paths.schema));
  if (invalid.length) return invalid;

  let manifest;
  try {
    manifest = readJson(paths.manifest);
  } catch {
    return [`${path.relative(repo, paths.manifest)} is missing. ${FIX}`];
  }

  const declared = new Map(doc.sounds.map((sound) => [sound.id, sound]));
  for (const id of declared.keys()) {
    if (!manifest.sounds?.[id]) {
      problems.push(`"${id}" is in sounds.json but was never built. ${FIX}`);
    }
  }
  const expectedFiles = new Set();
  for (const [id, built] of Object.entries(manifest.sounds ?? {})) {
    const sound = declared.get(id);
    if (!sound) {
      problems.push(`"${id}" was built but is not in sounds.json. ${FIX}`);
      continue;
    }
    if (!sameValue(built.declared, sound)) {
      const fields = [
        ...new Set([...Object.keys(built.declared), ...Object.keys(sound)]),
      ].filter((key) => !sameValue(built.declared[key], sound[key]));
      problems.push(
        `"${id}" changed in sounds.json since it was built (${fields.join(', ')}). ${FIX}`,
      );
      continue;
    }
    // The built variants are the declared ones, master for master.
    if (
      !sameValue(
        masters(built.variants ?? [], 'source', 'sourceSha256'),
        masters(sound.variants, 'file', 'sha256'),
      )
    ) {
      problems.push(
        `"${id}" was built from other masters than sounds.json declares. ${FIX}`,
      );
    }
    for (const variant of built.variants) {
      const key = encodeKey({
        sourceSha256: variant.sourceSha256,
        loudness: sound.loudness,
        channels: variant.channels,
      });
      if (key !== variant.encodeKey) {
        problems.push(
          `"${id}" ${variant.source} is encoded for other settings. ${FIX}`,
        );
      }
      for (const format of ['m4a', 'webm']) {
        const { file, sha256: expected, bytes } = variant.files[format];
        expectedFiles.add(file);
        const full = path.join(paths.filesDir, file);
        const named = outputName(id, variant.source, format);
        if (file !== named) {
          problems.push(
            `"${id}" ${variant.source} is in ${file}, not ${named}. ${FIX}`,
          );
        }
        if (!fs.existsSync(full)) {
          problems.push(`generated/files/${file} is missing. ${FIX}`);
          continue;
        }
        const content = fs.readFileSync(full);
        if (sha256(content) !== expected) {
          problems.push(
            `generated/files/${file} differs from the build; it was edited or replaced. ${FIX}`,
          );
        } else if (!CONTAINERS[format](content)) {
          problems.push(
            `generated/files/${file} is not ${format} audio. ${FIX}`,
          );
        }
        if (bytes !== content.length) {
          problems.push(
            `generated/files/${file} is ${content.length} bytes; the manifest says ${bytes}. ${FIX}`,
          );
        }
        const limit = CLASSES[sound.loudness].maxBytes;
        if (content.length > limit) {
          problems.push(
            `generated/files/${file} is ${content.length} bytes; a ${sound.loudness} file is at most ${limit}. ${FIX}`,
          );
        }
      }
    }
  }
  const present = fs.existsSync(paths.filesDir)
    ? fs.readdirSync(paths.filesDir)
    : [];
  for (const file of present) {
    if (!expectedFiles.has(file)) {
      problems.push(`generated/files/${file} is not in the manifest. ${FIX}`);
    }
  }

  const modules = renderModules(manifest);
  for (const [name, content] of modules) {
    const full = path.join(paths.outDir, name);
    const actual = fs.existsSync(full) ? fs.readFileSync(full, 'utf8') : null;
    if (actual !== content) {
      problems.push(`generated/${name} is not what the manifest makes. ${FIX}`);
    }
  }
  for (const name of fs.readdirSync(paths.outDir)) {
    if (name.endsWith('.ts') && !modules.has(name)) {
      problems.push(
        `generated/${name} is not a module the build writes. ${FIX}`,
      );
    }
  }
  return problems;
}
